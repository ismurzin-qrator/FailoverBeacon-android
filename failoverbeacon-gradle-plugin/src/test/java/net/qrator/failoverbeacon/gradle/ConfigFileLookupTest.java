package net.qrator.failoverbeacon.gradle;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertTrue;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import net.qrator.failoverbeacon.gradle.fakes.AndroidAppProject;
import org.gradle.testkit.runner.BuildResult;
import org.gradle.testkit.runner.TaskOutcome;
import org.junit.Rule;
import org.junit.Test;
import org.junit.rules.TemporaryFolder;

public final class ConfigFileLookupTest {
    private static final String CONFIG = "{ \"beacons\": [\"https://beacon.example\"] }";
    private static final String GENERATE_DEBUG = "generateDebugFailoverBeaconConfig";

    @Rule public final TemporaryFolder folder = new TemporaryFolder();

    @Test
    public void eachVariantTakesTheFirstFileInLookupOrder() throws IOException {
        AndroidAppProject project =
                AndroidAppProject.create(
                        root(),
                        "    flavorDimensions.addAll(['tier', 'store'])",
                        "    productFlavors {",
                        "        free { dimension = 'tier' }",
                        "        paid { dimension = 'tier' }",
                        "        play { dimension = 'store' }",
                        "        web { dimension = 'store' }",
                        "    }");
        for (String sourceSet :
                new String[] {"freePlayDebug", "freePlay", "play", "release", "main"}) {
            project.writeConfig(sourceSet, CONFIG);
        }

        project.runner(
                        generate("FreePlayDebug"),
                        generate("FreePlayRelease"),
                        generate("PaidPlayRelease"),
                        generate("PaidWebRelease"),
                        generate("PaidWebDebug"))
                .build();

        assertGeneratedFrom(project, "FreePlayDebug", "freePlayDebug");
        assertGeneratedFrom(project, "FreePlayRelease", "freePlay");
        assertGeneratedFrom(project, "PaidPlayRelease", "play");
        assertGeneratedFrom(project, "PaidWebRelease", "release");
        assertGeneratedFrom(project, "PaidWebDebug", "main");
    }

    @Test
    public void missingFileFailsTheBuildWithTheSearchedPaths() throws IOException {
        AndroidAppProject project = AndroidAppProject.create(root());

        BuildResult result = project.runner(GENERATE_DEBUG).buildAndFail();

        String expected =
                "No config file for variant debug. Searched: src/debug/failoverbeacon.json,"
                        + " src/main/failoverbeacon.json";
        assertTrue(result.getOutput(), result.getOutput().contains(expected));
    }

    @Test
    public void unchangedFileReusesTheConfigurationCacheAndSkipsTheTask() throws IOException {
        AndroidAppProject project = AndroidAppProject.create(root());
        project.writeConfig("main", CONFIG);
        project.runner(GENERATE_DEBUG).build();

        BuildResult result = project.runner(GENERATE_DEBUG).build();

        assertTrue(result.getOutput(), result.getOutput().contains("Reusing configuration cache."));
        assertEquals(TaskOutcome.UP_TO_DATE, result.task(":" + GENERATE_DEBUG).getOutcome());
    }

    @Test
    public void newFileEarlierInLookupOrderRerunsTheTask() throws IOException {
        AndroidAppProject project = AndroidAppProject.create(root());
        project.writeConfig("main", CONFIG);
        project.runner(GENERATE_DEBUG).build();
        project.writeConfig("debug", CONFIG);

        BuildResult result = project.runner(GENERATE_DEBUG).build();

        assertEquals(TaskOutcome.SUCCESS, result.task(":" + GENERATE_DEBUG).getOutcome());
        assertGeneratedFrom(project, "Debug", "debug");
    }

    @Test
    public void fileMovedWithTheSameContentRerunsTheTask() throws IOException {
        AndroidAppProject project = AndroidAppProject.create(root());
        project.writeConfig("main", CONFIG);
        project.runner(GENERATE_DEBUG).build();
        Files.delete(root().resolve("src/main/" + AndroidAppProject.CONFIG_FILE));
        project.writeConfig("debug", CONFIG);

        BuildResult result = project.runner(GENERATE_DEBUG).build();

        assertEquals(TaskOutcome.SUCCESS, result.task(":" + GENERATE_DEBUG).getOutcome());
        assertGeneratedFrom(project, "Debug", "debug");
    }

    private Path root() {
        return folder.getRoot().toPath();
    }

    private static String generate(String variant) {
        return "generate" + variant + "FailoverBeaconConfig";
    }

    private static void assertGeneratedFrom(
            AndroidAppProject project, String variant, String sourceSet) throws IOException {
        String header =
                "// Generated by the FailoverBeacon Gradle plugin from src/"
                        + sourceSet
                        + "/failoverbeacon.json.";
        String source = project.generatedSource(generate(variant));
        assertTrue(variant + ": " + source, source.startsWith(header));
    }
}
